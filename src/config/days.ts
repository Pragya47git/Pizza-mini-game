export function getDayConfig(dayNumber: number): DayConfig {
  if (dayNumber <= DAY_CONFIGS.length) {
    return DAY_CONFIGS[dayNumber - 1];
  }
  // Endless master days past Day 10
  const bonusMultiplier = dayNumber - DAY_CONFIGS.length;
  return {
    day: dayNumber,
    shiftDuration: 110,
    targetRevenue: 400 + bonusMultiplier * 50,
    maxActiveCustomers: 4,
    customerSpawnMinInterval: 3,
    customerSpawnMaxInterval: 6.5,
    allowedRecipes: ['margherita', 'pepperoni', 'mushroom_delight', 'veggie_supreme', 'four_cheese', 'rustic_basilico', 'spicy_diablo'],
    allowedCustomerTypes: ['regular', 'impatient', 'generous', 'vip', 'special_request'],
    narrativeIntro: `Day ${dayNumber} - Pizzeria Master Mode! Can you keep up with the legendary neighborhood demand?`,
    completionBonus: 100 + bonusMultiplier * 20,
  };
}
